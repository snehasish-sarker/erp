                            </span>

                            <span v-if="tenant.phone">
                                {{ tenant.phone }}
                            </span>
                        </div>
                    </div>
                </div>

                <div class="ap-print-generated-meta">
                    <div>
                        <strong>Generated:</strong>
                        {{ generatedAt }}
                    </div>

                    <div>
                        <strong>Generated by:</strong>
                        {{ generatedBy.name }}
                    </div>

                    <div>
                        <strong>User:</strong>
                        {{ generatedBy.email }}
                    </div>
                </div>
            </header>

            <slot />

            <footer class="ap-print-footer">
                <span>
                    Confidential tenant financial report
                </span>

                <span>
                    Base currency:
                    {{ tenant.currency_code }}
                    · Timezone:
                    {{ tenant.timezone }}
                </span>
            </footer>
        </main>
    </div>
</template>

