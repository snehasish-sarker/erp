                class="ap-print-button"
                @click="closeWindow"
            >
                Close
            </button>

            <button
                type="button"
                class="ap-print-button ap-print-button-primary"
                @click="printDocument"
            >
                Print / Save PDF
            </button>
        </div>

        <main class="ap-print-document">
            <header class="ap-print-header">
