<script setup lang="ts">
import { Head } from '@inertiajs/vue3';
import {
    nextTick,
    onMounted,
} from 'vue';

interface PrintTenant {
    name: string;
    code: string;
    email: string | null;
    phone: string | null;
    address: string | null;
    currency_code: string;
    timezone: string;
}

interface PrintGeneratedBy {
    id: number;
    name: string;
    email: string;
}

interface Props {
    title: string;
    tenant: PrintTenant;
    generatedBy: PrintGeneratedBy;
    generatedAt: string;
    autoprint?: boolean;
}

const props = withDefaults(
    defineProps<Props>(),
    {
        autoprint: false,
    },
);

const printDocument = (): void => {
    window.print();
};

const closeWindow = (): void => {
    window.close();
};

onMounted(
    async (): Promise<void> => {
        if (!props.autoprint) {
            return;
        }

        await nextTick();

        window.requestAnimationFrame(
            (): void => {
                window.requestAnimationFrame(
                    (): void => {
                        window.print();
                    },
                );
            },
        );
    },
);
</script>

<template>
    <Head :title="title" />

    <div class="ap-print-page">
        <div class="ap-print-toolbar">
            <button
